# Installs EVERYTHING you need to program Stack-chan on Windows 10/11,
# starting from a bare computer: Git, Python, VS Code + PlatformIO, the
# ESP32-S3 toolchain and the project environment.
#
#   Double-click setup.bat, or in PowerShell:
#   powershell -ExecutionPolicy Bypass -File setup.ps1 [-Wifi] [-Flash] [-NoSystem]
#
# You can run it as many times as you need: whatever is installed is skipped.
param([switch]$Wifi, [switch]$Flash, [switch]$NoSystem)
# Native tools report failure through $LASTEXITCODE; "Stop" would abort on any stderr output in PowerShell 5.1.
$ErrorActionPreference = "Continue"
Set-Location $PSScriptRoot
$Root = $PSScriptRoot
$Venv = Join-Path $Root ".venv"
$Py = Join-Path $Venv "Scripts\python.exe"
$Pio = Join-Path $Venv "Scripts\pio.exe"
$Secrets = Join-Path $Root "config\wifi_secrets.h"

function Bold($m) { Write-Host "`n$m" -ForegroundColor White }
function Ok($m)   { Write-Host "  [OK] $m" -ForegroundColor Green }
function Warn($m) { Write-Host "  [!]  $m" -ForegroundColor Yellow }
function Die($m)  { Write-Host "  [X]  $m" -ForegroundColor Red; exit 1 }
function Have($c) { [bool](Get-Command $c -ErrorAction SilentlyContinue) }
function Refresh-Path {
    $env:Path = [Environment]::GetEnvironmentVariable("Path", "Machine") + ";" + [Environment]::GetEnvironmentVariable("Path", "User")
}

function Ask-Wifi {
    Bold "Robot Wi-Fi"
    Write-Host "  The robot, the laptop and the phone must be on the SAME 2.4 GHz Wi-Fi network."
    $ssid = Read-Host "  Network name (SSID)"
    if (-not $ssid) { Die "The SSID can't be empty" }
    $sec = Read-Host "  Password (not shown)" -AsSecureString
    $pass = [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec))
    function CStr($s) { '"' + $s.Replace('\', '\\').Replace('"', '\"') + '"' }
    $content = "// Generated by setup. Do NOT commit it (it is in .gitignore).`n#pragma once`n" +
               "#define WIFI_SSID $(CStr $ssid)`n#define WIFI_PASS $(CStr $pass)`n"
    [IO.File]::WriteAllText($Secrets, $content, (New-Object Text.UTF8Encoding $false))
    Ok "Saved to config\wifi_secrets.h (all the firmwares use it)"
}

if ($Wifi) {
    if (-not (Test-Path $Py)) { Die "Run setup.bat first" }
    Ask-Wifi
    exit 0
}

if (-not $NoSystem) {
    Bold "1/6 Programs (winget)"
    if (-not (Have winget)) { Die "winget is missing. Install 'App Installer' from the Microsoft Store and run this again." }
    $apps = @(
        @{ Id = "Git.Git"; Cmd = "git"; Name = "Git" },
        @{ Id = "Python.Python.3.12"; Cmd = "py"; Name = "Python 3.12" },
        @{ Id = "Microsoft.VisualStudioCode"; Cmd = "code"; Name = "Visual Studio Code" }
    )
    foreach ($a in $apps) {
        if (Have $a.Cmd) { Ok "$($a.Name) already installed"; continue }
        Write-Host "  Installing $($a.Name)..."
        winget install --id $a.Id -e --silent --accept-package-agreements --accept-source-agreements | Out-Null
        Refresh-Path
        if (Have $a.Cmd) { Ok "$($a.Name)" } else { Warn "$($a.Name) installed; if it is not found, close and reopen the terminal and try again" }
    }
    if (Have code) {
        foreach ($ext in @("platformio.platformio-ide", "ms-python.python")) {
            code --install-extension $ext --force 2>$null | Out-Null
        }
        Ok "VS Code extensions: PlatformIO IDE and Python"
    }

    # The CoreS3 uses the ESP32-S3's native USB (303A:1001): Windows 10/11 usually
    # installs the driver by itself (with Internet). If it fails, see docs/ROBOT.md.

    $admin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
    if ($admin) {
        if (-not (Get-NetFirewallRule -DisplayName "Stack-chan VR" -ErrorAction SilentlyContinue)) {
            New-NetFirewallRule -DisplayName "Stack-chan VR" -Direction Inbound -Protocol UDP -LocalPort 5600-5601 -Action Allow -Profile Private,Domain | Out-Null
        }
        Ok "Firewall: UDP 5600-5601 open on private networks"
    } else {
        Warn "Firewall: the first time you start the relay, Windows will ask. Tick 'Private networks' and click Allow."
        Warn "And check that your Wi-Fi is set as a PRIVATE network (Settings > Network > Wi-Fi > properties)."
    }
}

Bold "2/6 Project Python environment (.venv)"
Refresh-Path
if (-not (Test-Path $Py)) {
    if (Have py) { py -3 -m venv $Venv } elseif (Have python) { python -m venv $Venv } else { Die "Can't find Python. Close and reopen the terminal and try again." }
}
& $Py -m pip install --quiet --upgrade pip
& $Py -m pip install --quiet -r requirements.txt
if ($LASTEXITCODE) { Die "Installing the Python dependencies failed" }
Ok "platformio, opencv-python, numpy, pyserial"

Bold "3/6 ESP32 and ESP32-S3 toolchains (~1 GB download the first time)"
$Projects = Get-ChildItem demos -Recurse -Filter platformio.ini | Where-Object { $_.FullName -notmatch '\\.pio\\' } | ForEach-Object { $_.DirectoryName }
foreach ($p in $Projects) {
    & $Pio pkg install --project-dir $p | Out-Null
    if ($LASTEXITCODE) { Die "Downloading the toolchain for $p failed" }
}
Ok "Compilers, Arduino-ESP32 framework and the libraries of every demo"

Bold "4/6 Robot Wi-Fi"
if (Test-Path $Secrets) { Ok "Already set up. To change it: setup.bat -Wifi" } else { Ask-Wifi }

Bold "5/6 Check"
& $Py -m unittest discover -s lib/python/tests 2>$null | Out-Null
if ($LASTEXITCODE) { Warn "The relay tests fail" } else { Ok "Relay tests" }
foreach ($p in $Projects) {
    & $Pio run --project-dir $p --silent | Out-Null
    if ($LASTEXITCODE) { Die "${p} does not build: .venv\Scripts\pio run -d $p" }
    Ok "Builds $(Resolve-Path -Relative $p)"
}

Bold "6/6 Robot on USB"
$ports = & $Pio device list --json-output 2>$null | ConvertFrom-Json | Where-Object { $_.hwid -match "303A" }
if ($ports) { Ok "Robot found on $($ports[0].port)" } else {
    Warn "Can't see the robot on USB (normal if it is not connected)."
    Warn "If it is connected and Device Manager shows 'USB JTAG/serial debug unit' with no COM port,"
    Warn "the driver is missing: see docs\ROBOT.md, section 'USB port on each system'."
}
if ($Flash) { & (Join-Path $Root "tools\flash.ps1") -Project "demos\01-vr-cardboard\firmware" }

Bold "Done!"
Write-Host "  Open the project in VS Code:   code stackchan-course.code-workspace"
Write-Host "  First demo:                    demos\01-vr-cardboard\README.md"
Write-Host "  Flash a firmware:              tools\flash.bat   (with no arguments it lists them)"
Write-Host "  AI assistant (optional):       irm https://claude.ai/install.ps1 | iex   (Claude Code)"
Write-Host "  Demo 02 (voice):               needs GEMINI_API_KEY, see demos\02-gemini-voice\README.md"
