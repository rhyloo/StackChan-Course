#!/usr/bin/env bash
# Installs EVERYTHING you need to program Stack-chan on Linux (Ubuntu/Debian),
# starting from a bare computer: Git, Python, VS Code + PlatformIO, the
# ESP32-S3 toolchain, USB port permissions and the project environment.
#
#     ./setup.sh               full install (asks for sudo for the system parts)
#     ./setup.sh --no-system   no sudo: only the project environment (.venv, toolchain, Wi-Fi)
#     ./setup.sh --wifi        only asks for the robot's Wi-Fi again
#     ./setup.sh --flash       at the end, flashes demo 01 to the robot connected over USB
#
# You can run it as many times as you need: whatever is installed is skipped.
set -euo pipefail
cd "$(dirname "$0")"
ROOT=$(pwd)
VENV="$ROOT/.venv"
SECRETS="$ROOT/config/wifi_secrets.h"
UDEV_RULES=/etc/udev/rules.d/99-platformio-udev.rules
UDEV_URL=https://raw.githubusercontent.com/platformio/platformio-core/develop/platformio/assets/system/99-platformio-udev.rules

bold() { printf '\n\033[1m%s\033[0m\n' "$*"; }
ok()   { printf '  \033[32m✔\033[0m %s\n' "$*"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*"; }
die()  { printf '  \033[31m✘ %s\033[0m\n' "$*"; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }

ask_wifi() {
    bold "Robot Wi-Fi"
    echo "  The robot, the laptop and the phone must be on the SAME 2.4 GHz Wi-Fi network"
    echo "  (the ESP32-S3 can't see 5 GHz networks)."
    local ssid="${WIFI_SSID:-}" pass="${WIFI_PASS:-}"
    [ -n "$ssid" ] || read -r -p "  Network name (SSID): " ssid
    [ -n "$pass" ] || { read -r -s -p "  Password (not shown): " pass; echo; }
    [ -n "$ssid" ] || die "The SSID can't be empty"
    WIFI_SSID="$ssid" WIFI_PASS="$pass" "$VENV/bin/python" - "$SECRETS" <<'PY'
import os, sys
def c(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
with open(sys.argv[1], "w") as f:
    f.write("// Generated by setup. Do NOT commit it (it is in .gitignore).\n#pragma once\n")
    f.write(f"#define WIFI_SSID {c(os.environ['WIFI_SSID'])}\n#define WIFI_PASS {c(os.environ['WIFI_PASS'])}\n")
PY
    chmod 600 "$SECRETS"
    ok "Saved to config/wifi_secrets.h (all the firmwares use it)"
}

SYSTEM=1 FLASH=0 WIFI_ONLY=0
for arg in "$@"; do
    case "$arg" in
        --no-system) SYSTEM=0 ;;
        --flash) FLASH=1 ;;
        --wifi) WIFI_ONLY=1 ;;
        -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
        *) die "Unknown option: $arg (use --help)" ;;
    esac
done

if [ "$WIFI_ONLY" = 1 ]; then
    [ -x "$VENV/bin/python" ] || die "Run ./setup.sh first"
    ask_wifi
    exit 0
fi

[ "$(uname)" = Linux ] || die "This script is for Linux. On Windows use setup.ps1 (see README)."

# ---------------------------------------------------------------------------
if [ "$SYSTEM" = 1 ]; then
    bold "1/7 System packages (apt)"
    have apt-get || die "Can't find apt-get. Install by hand: git python3 python3-venv python3-pip curl, and come back with --no-system"
    PKGS=(git curl python3 python3-venv python3-pip)
    MISSING=()
    for p in "${PKGS[@]}"; do dpkg -s "$p" >/dev/null 2>&1 || MISSING+=("$p"); done
    if [ ${#MISSING[@]} -gt 0 ]; then
        echo "  Installing: ${MISSING[*]} (it will ask for your user password)"
        sudo apt-get update -qq
        sudo apt-get install -y -qq "${MISSING[@]}"
    fi
    ok "git, curl, python3, venv and pip"

    bold "2/7 Permissions for the robot's USB port"
    # The CoreS3 uses the ESP32-S3's native USB (it shows up as /dev/ttyACM0): it
    # needs no driver, but it does need permission to open the port.
    if [ ! -f "$UDEV_RULES" ]; then
        curl -fsSL "$UDEV_URL" | sudo tee "$UDEV_RULES" >/dev/null
        sudo udevadm control --reload-rules && sudo udevadm trigger
    fi
    ok "PlatformIO udev rules"
    if id -nG "$USER" | grep -qw dialout; then
        ok "Your user is in the dialout group"
    else
        sudo usermod -aG dialout "$USER"
        warn "I added you to the dialout group: LOG OUT and back in for it to take effect."
    fi
    if dpkg -s brltty >/dev/null 2>&1; then
        # brltty (braille reader) grabs some USB serial ports on Ubuntu.
        warn "brltty is installed and sometimes takes over the USB port. If the robot doesn't show up: sudo apt remove brltty"
    fi

    bold "3/7 Visual Studio Code"
    if have code; then
        ok "Already installed ($(code --version 2>/dev/null | head -1))"
    elif have snap; then
        sudo snap install code --classic
        ok "Installed with snap"
    else
        # Microsoft's official repository.
        sudo apt-get install -y -qq wget gpg apt-transport-https
        wget -qO- https://packages.microsoft.com/keys/microsoft.asc | gpg --dearmor | sudo tee /usr/share/keyrings/microsoft.gpg >/dev/null
        echo "deb [arch=amd64,arm64,armhf signed-by=/usr/share/keyrings/microsoft.gpg] https://packages.microsoft.com/repos/code stable main" \
            | sudo tee /etc/apt/sources.list.d/vscode.list >/dev/null
        sudo apt-get update -qq && sudo apt-get install -y -qq code
        ok "Installed from Microsoft's repository"
    fi
    if have code; then
        for ext in platformio.platformio-ide ms-python.python; do
            code --list-extensions 2>/dev/null | grep -qi "^$ext$" || code --install-extension "$ext" --force >/dev/null 2>&1 || true
        done
        ok "Extensions: PlatformIO IDE and Python"
    fi

    if have ufw && sudo ufw status 2>/dev/null | grep -q 'Status: active'; then
        sudo ufw allow 5600:5601/udp >/dev/null
        ok "Firewall: UDP 5600-5601 open (robot and phone)"
    fi
fi

# ---------------------------------------------------------------------------
bold "4/7 Project Python environment (.venv)"
python3 -c 'import sys; sys.exit(sys.version_info < (3, 9))' || die "You need Python 3.9 or newer (you have $(python3 --version))"
python3 -c 'import venv, ensurepip' 2>/dev/null || die "python3-venv is missing: sudo apt install python3-venv"
[ -x "$VENV/bin/python" ] || python3 -m venv "$VENV"
"$VENV/bin/python" -m pip install --quiet --upgrade pip
"$VENV/bin/python" -m pip install --quiet -r requirements.txt
ok "$("$VENV/bin/pip" list 2>/dev/null | grep -i -E '^(platformio|opencv-python|numpy) ' | awk '{printf "%s %s  ", $1, $2}')"

bold "5/7 ESP32 and ESP32-S3 toolchains (~1 GB download the first time)"
PROJECTS=$(find demos -name platformio.ini -not -path '*/.pio/*' -exec dirname {} \; | sort)
for p in $PROJECTS; do
    "$VENV/bin/pio" pkg install --project-dir "$p" >/dev/null
done
ok "Compilers, Arduino-ESP32 framework and the libraries of every demo"

bold "6/7 Robot Wi-Fi"
if [ -f "$SECRETS" ]; then
    ok "Already set up. To change it: ./setup.sh --wifi"
else
    ask_wifi
fi

bold "7/7 Check"
"$VENV/bin/python" -m unittest discover -s lib/python/tests >/dev/null 2>&1 && ok "Relay tests" || warn "Tests fail: .venv/bin/python -m unittest discover -s lib/python/tests -v"
for p in $PROJECTS; do
    "$VENV/bin/pio" run --project-dir "$p" --silent >/dev/null && ok "Builds $p" || die "$p does not build: .venv/bin/pio run -d $p"
done
if ls /dev/ttyACM* >/dev/null 2>&1; then ok "Robot found on $(ls /dev/ttyACM* | head -1)"; else warn "Can't see the robot on USB (normal if it is not connected)"; fi

if [ "$FLASH" = 1 ]; then ./tools/flash.sh demos/01-vr-cardboard/firmware; fi

bold "Done!"
cat <<MSG
  Open the project in VS Code:   code stackchan-course.code-workspace
  First demo:                    cat demos/01-vr-cardboard/README.md
  Flash a firmware:              ./tools/flash.sh   (with no arguments it lists them)
  AI assistant (optional):       curl -fsSL https://claude.ai/install.sh | bash   (Claude Code)
  Demo 02 (voice):               needs GEMINI_API_KEY, see demos/02-gemini-voice/README.md
MSG
